import { test, expect } from "@playwright/test";
import { InventoryPage } from "../pages/inventoryPage";
import { CartPage } from "../pages/cartPage";
import { LoginPage } from "../pages/loginPage";
import { CheckoutPage } from "../pages/checkoutPage";
const username = "standard_user";
const password = "secret_sauce";
const productName = "Sauce Labs Backpack";
test("Complete product order for logged-in user", async ({ page }) => {
  const inventoryPage = new InventoryPage(page);
  const cartPage = new CartPage(page);
  const loginPage = new LoginPage(page);
  const checkoutPage = new CheckoutPage(page);
  await page.goto("/");
  await loginPage.login(username, password);
  await loginPage.verifySuccessfulLogin();
  await inventoryPage.selectProduct(productName);
  await inventoryPage.openCart.click();
  await expect(cartPage.inventory_item_name).toHaveText(productName);
  await cartPage.checkout.click();
  await checkoutPage.enterCustomerDetails("Hari", "Kishore", "600001");
  await checkoutPage.finishOrderBtn.click();
  await expect(page).toHaveURL(/checkout-complete.html/);
  await checkoutPage.verifyOrderConfirmation(); 
});
